// ─── ضريبة القيمة المضافة ─────────────────────────────────────────────────────
// الأسعار في المنصة معلنة بلا ضريبة، وتُضاف عند الدفع.
//
// الضريبة **ليست إيراداً** — هي مبلغ يُحصَّل نيابةً عن هيئة الزكاة والضريبة
// ويُورَّد لها. لذلك تُخزَّن منفصلة في عمود vatAmount، ويطرحها تقرير الإيرادات
// من المبلغ المحصَّل. لو حُسبت ضمن الإيراد لبدت الأرباح أعلى 15% مما هي.

/** نسبة ضريبة القيمة المضافة في السعودية */
export const VAT_RATE = 0.15;

/**
 * تفصيل مبلغ معلن (بلا ضريبة) إلى صافٍ وضريبة وإجمالي.
 *
 * الإجمالي يُقرَّب أولاً ثم تُشتق الضريبة بالطرح، لا العكس: لو قُرِّب كل رقم
 * على حدة لظهرت صفوف يكون فيها صافٍ + ضريبة ≠ إجمالي بفرق هللة، فيتوقف
 * (amount - vatAmount) عن مساواة السعر المعلن للعميل.
 */
export function withVat(net: number): { net: number; vat: number; total: number } {
  const roundedNet = Math.round(net * 100) / 100;
  const total = Math.round(roundedNet * (1 + VAT_RATE) * 100) / 100;
  return { net: roundedNet, vat: Math.round((total - roundedNet) * 100) / 100, total };
}
