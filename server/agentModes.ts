const ACCOUNTING_IDENTITY_BASE =
  "تجمع في شخص واحد ثلاثة خبراء: **محاسب مالي خبير** و**رئيس حسابات** و**خبير معتمد في ERPNext**";

export function identityLineFor(mode: AgentMode, hasCfoSkill: boolean): string {
  if (mode === "expert") {
    return "أنت **مستشار تطبيق أنظمة ERP** — خبير معتمد في ERPNext وOdoo بخبرة تنفيذ وتقييم لدى شركات متعددة. "
      + "تتقن: تصميم دورات العمل (Workflows) وحالات المستندات والموافقات، وكتابة السياسات والإجراءات المحاسبية والتشغيلية بما يناسب حجم الشركة ونشاطها، "
      + "وتقييم نظام قائم واستلامه من مزوّد الخدمة وإعداد بنود الاستلام والتسليم، ومراجعة ما إذا كان المنفَّذ يطابق المتفق عليه، "
      + "وضبط الإعدادات والتخصيصات، وتصميم نماذج طباعة المستندات (Print Formats) وتنسيقها.";
  }
  return hasCfoSkill
    ? "تجمع في شخص واحد أربعة خبراء: **محاسب مالي خبير** و**مدير مالي (CFO)** و**رئيس حسابات** و**خبير معتمد في ERPNext**."
    : `${ACCOUNTING_IDENTITY_BASE} — تنفّذ الطلبات بدقة ومباشرة دون تحليلات إدارية إضافية.`;
}

/**
 * أدوات ممنوعة على وضع الخبير: كل ما يُنشئ سجلاً أو يغيّر حالة مستند.
 * الخبير يقرأ ويضبط الإعدادات — ولا يُدخل بيانات ولا حركات.
 */
export const EXPERT_BLOCKED_TOOLS = new Set([
  // حركات محاسبية
  "create_invoice", "submit_invoice",
  "create_purchase_invoice",
  "create_payment_entry",
  "create_journal_entry",
  "submit_document",
  // تغيير حالة أو محتوى مستند قائم
  "update_document", "cancel_document", "delete_document",
  // بيانات أساسية — التقييم لا يستلزم إنشاء سجلات عند العميل
  "create_customer", "create_supplier", "create_item",
]);

export function toolsForMode<T extends { function: { name: string } }>(
  tools: T[], mode: AgentMode,
): T[] {
  if (mode !== "expert") return tools;
  return tools.filter(t => !EXPERT_BLOCKED_TOOLS.has(t.function.name));
}

/** الكتلة النصية التي تُضاف لبرومبت الوضع */
export function modeRulesFor(mode: AgentMode): string {
  return mode === "expert" ? `${GOVERNANCE_RULES}\n\n${EXPERT_RULES}` : GOVERNANCE_RULES;
}
