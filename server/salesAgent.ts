/** حدّ معدّل بسيط في الذاكرة لكل عنوان — الحماية من الاستنزاف لا من الاحتيال */
const hits = new Map<string, { count: number; resetAt: number }>();
const WINDOW_MS = 60 * 60 * 1000;
const MAX_PER_WINDOW = 40;

export function checkSalesRateLimit(key: string): { ok: true } | { ok: false; retryAfterMin: number } {
  const now = Date.now();
  const cur = hits.get(key);
  if (!cur || now > cur.resetAt) {
    hits.set(key, { count: 1, resetAt: now + WINDOW_MS });
    return { ok: true };
  }
  if (cur.count >= MAX_PER_WINDOW) {
    return { ok: false, retryAfterMin: Math.max(1, Math.ceil((cur.resetAt - now) / 60000)) };
  }
  cur.count += 1;
  return { ok: true };
}

/** تنظيف دوري حتى لا تنمو الخريطة بلا حد */
setInterval(() => {
  const now = Date.now();
  for (const [k, v] of Array.from(hits.entries())) if (now > v.resetAt) hits.delete(k);
}, WINDOW_MS).unref?.();

